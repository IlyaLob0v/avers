using System.Globalization;
using Avers.Domain;

namespace Avers.Desktop.Printing;

/// <summary>
/// Заявление о выдаче судебного приказа по образцу юристов (21.10.2026). Долг и неустойка — на дату заявления
/// (<see cref="Penalty"/>). Чего в Аверсе нет (номер участка, уведомление, госпошлина, паспорт, дата рождения),
/// остаётся пустым местом, юрист вписывает в Word.
/// </summary>
public static class CourtOrderApplication
{
    private static readonly CultureInfo Ru = CultureInfo.GetCultureInfo("ru-RU");
    private const string Blank = "«___» _________ 20___";

    public static (string[] Header, string Title, string[] Body) Text(Subscriber s, DateOnly date)
    {
        var lines = Penalty.Calculate(s.Payments, date);
        var debt = lines.Sum(l => l.Debt);
        var penalty = lines.Sum(l => l.Amount);
        var claimed = Penalty.Claimed(lines);
        var address = $"г. Омск, {s.House.AddressLine}, кв. {s.Apartment}";
        var contract = s.ContractDate is { } cd ? $"{cd:dd.MM.yyyy}" : Blank;
        var first = lines.FirstOrDefault();
        var last = lines.LastOrDefault();
        var period = first is null ? "___" : $"{Month(first.Year, first.Month, true)} по {Month(last!.Year, last.Month, false)}";
        var byYear = string.Join(", ", lines.GroupBy(l => l.Year).Select(g => $"за {g.Key} год — {Money(g.Sum(l => l.Debt))} руб."));
        var tariff = first is null ? "___" : Money(s.Payments.First(p => p.Year == first.Year && p.Month == first.Month).Tariff);
        var stopped = s.ContractTerminated is { } t
            ? $"На основании положений договора и действующего законодательства, в связи с неоплатой, Взыскателем было приостановлено оказание услуг {t:dd.MM.yyyy} года, начисление абонентской платы прекращено."
            : "";
        var penaltyText = penalty > debt
            ? $"По состоянию на {date:dd.MM.yyyy} сумма неустойки составила {Money(penalty)} руб. Руководствуясь ст. 333 ГК РФ, Взыскатель добровольно снизил размер неустойки до суммы основного долга — {MoneyWords.Rubles(claimed)}."
            : $"По состоянию на {date:dd.MM.yyyy} сумма неустойки составила {MoneyWords.Rubles(claimed)}.";

        string[] header =
        [
            "Мировому судье судебного участка № ___",
            "в ________________ судебном районе в г. Омске",
            "Взыскатель: ООО «Производственное объединение «Аверс-Сервис»,",
            "ИНН 5503254160, ОГРН 1145543048001,",
            "644007, г. Омск, ул. Третьяковская, д. 73",
            $"Должник: {s.ContractParty},",
            $"адрес: {address}"
        ];
        string[] body =
        [
            $"{contract} года между ООО «ПО «Аверс-Сервис» (Взыскатель) и Должником (Абонентом) — {s.ContractParty} был заключен договор{(s.ContractNumber == "" ? "" : $" № {s.ContractNumber}")} на предоставление услуг по техническому обслуживанию цифровых систем коллективного приема телевидения. В соответствии с условиями договора Взыскатель принял на себя обязательства по техническому обслуживанию систем коллективного приема телевидения (СКПТ) по адресу фактического проживания и нахождения абонентского отвода Должника: {address}, а Должник обязался своевременно принимать и оплачивать оказанные услуги.",
            "Согласно п. 5.2 Договора, оплата за пользование услугами производится Абонентом ежемесячно до 10 числа месяца, следующего за периодом платежа, по квитанциям установленного образца через почтовые отделения связи, кассу Объединения, отделения ПАО Сбербанк, систему «Сбербанк Онлайн» либо по единым платежным квитанциям.",
            "В соответствии со ст. 309, 310 Гражданского кодекса РФ обязательства должны исполняться надлежащим образом в соответствии с условиями обязательства и требованиями закона. Односторонний отказ от исполнения обязательства и одностороннее изменение его условий не допускаются.",
            "В период действия Договора Должник надлежащим образом обязанности по оплате не исполнял, в связи с чем образовалась задолженность. О прекращении пользования услугами Должник Взыскателя в известность не ставил, официальных заявлений на отключение в адрес ООО «ПО «Аверс-Сервис» не поступало.",
            $"На основании п. 2.3 Договора Взыскатель имеет право производить в одностороннем порядке изменение размера действующего тарифа за пользование СКПТ. На момент возникновения задолженности тариф оплаты за один подключенный абонентский отвод составлял {tariff} руб./мес.",
            $"В связи с систематическим неисполнением обязательств по оплате Должнику было направлено Досудебное уведомление № ___ от {Blank} года, которое было проигнорировано. {stopped}".TrimEnd(),
            $"За период с {period} у Должника образовалась задолженность в размере {MoneyWords.Rubles(debt)}, из которых: {byYear}",
            "На основании п. 1 ст. 330 ГК РФ неустойкой (штрафом, пеней) признается определенная законом или договором денежная сумма, которую должник обязан уплатить кредитору в случае неисполнения или ненадлежащего исполнения обязательства. Согласно п. 2.3 заключенного Договора, в случае неоплаты, неполной или несвоевременной оплаты услуг Взыскатель имеет право требовать уплаты неустойки в размере 1 % от суммы долга за каждый день просрочки.",
            $"{penaltyText} Общая сумма требований (основной долг и неустойка) составляет {MoneyWords.Rubles(debt + claimed)}.",
            "В соответствии со ст. 122 ГПК РФ судебный приказ выдается, если требование основано на сделке, совершенной в простой письменной форме. На основании ст. 333.19 Налогового кодекса РФ Взыскателем уплачена государственная пошлина в размере _______ рублей.",
            "Согласно п. 3 ч. 2 ст. 124 ГПК РФ в заявлении о вынесении судебного приказа должны быть указаны обязательные идентификаторы должника. В связи с отсутствием у Взыскателя полных данных о месте рождения должника, на основании абз. 2 ч. 3 ст. 124 ГПК РФ, Взыскатель заявляет ходатайство об их истребовании судом у компетентных органов.",
            "На основании изложенного, руководствуясь статьями 309, 310, 330 ГК РФ, статьями 121, 122, 123, 124 ГПК РФ,",
            "ПРОШУ:",
            $"1. Взыскать с Должника — {s.ContractParty} ({Blank} года рождения, место рождения: __________; зарегистрированного(-ой) по адресу: __________; паспорт серии _____ № _______) в пользу Общества с ограниченной ответственностью «Производственное объединение «Аверс-Сервис» (ИНН 5503254160) денежные средства в общем размере {MoneyWords.Rubles(debt + claimed)}, в том числе:",
            $"- задолженность по договору на техническое обслуживание цифровых систем коллективного приема телевидения от {contract} за период с {period} в размере {MoneyWords.Rubles(debt)};",
            $"- неустойку в размере {MoneyWords.Rubles(claimed)};",
            $"- расходы по оплате государственной пошлины в размере _______ рублей.",
            $"2. На основании ч. 3 ст. 124 ГПК РФ запросить в компетентных государственных органах полные сведения о месте рождения Должника ({s.ContractParty}) для указания в судебном приказе.",
            "Приложение:",
            "1. Платежное поручение об оплате государственной пошлины.",
            $"2. Копия договора от {contract} г.",
            $"3. Копия досудебного уведомления № ____ от {Blank} г.",
            $"4. Копия лицевого счета за {(first is null ? "___ г." : first.Year == last!.Year ? $"{first.Year} г." : $"{first.Year}–{last.Year} гг.")}",
            $"5. Копия калькуляции на предоставление услуг связи от {Blank} г.",
            $"6. Расчет неустойки от {date:dd.MM.yyyy} г.",
            "7. Копия Свидетельства о постановке на учет организации в налоговом органе по месту ее нахождения.",
            "8. Копия Свидетельства о регистрации юридического лица.",
            "9. Копия Свидетельства об удостоверении решения органа юридического лица.",
            "10. Копия устава Общества с ограниченной ответственностью «Производственное объединение «Аверс-Сервис»."
        ];
        return (header, "Заявление о выдаче судебного приказа", [.. body.Where(b => b != "")]);
    }

    /// <summary>«с декабря 2022 года по ноябрь 2023 года».</summary>
    private static string Month(int year, int month, bool genitive) =>
        $"{(genitive ? Ru.DateTimeFormat.MonthGenitiveNames : Ru.DateTimeFormat.MonthNames)[month - 1].ToLowerInvariant()} {year} года";

    private static string Money(decimal value) => value.ToString("0.00", Ru);
}
