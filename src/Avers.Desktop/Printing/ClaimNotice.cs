using Avers.Domain;

namespace Avers.Desktop.Printing;

public enum ClaimKind { Connected, DisconnectedForDebt, DisconnectedOnRequest }

public sealed record ClaimVariant(ClaimKind Kind, string Title);

/// <summary>
/// Досудебное уведомление по образцам юристов (21.10.2026): первая строка — заголовок, дальше абзацы.
/// Дата отключения — дата расторжения договора; если её нет, остаётся место, чтобы вписать от руки.
/// </summary>
public static class ClaimNotice
{
    public static IReadOnlyList<ClaimVariant> Variants { get; } =
    [
        new(ClaimKind.Connected, "Антенна подключена, договор есть"),
        new(ClaimKind.DisconnectedForDebt, "Отключили за долг"),
        new(ClaimKind.DisconnectedOnRequest, "Отключили по заявлению, договора нет")
    ];

    private const string Pay = "Оплату можно произвести через кассу нашего предприятия, по квитанции ООО «Омская энергосбытовая компания» (ООО «ОЭК»), через мобильное приложение «Сбербанк Онлайн», в любом отделении ПАО Сбербанк.";

    public static string Text(ClaimKind kind, string address, decimal debt, DateOnly? disconnected)
    {
        var sum = MoneyWords.Rubles(debt);
        var date = disconnected?.ToString("dd.MM.yyyy") ?? "«___» _________ 20___";
        var service = $"по лицевому счёту, закреплённому за квартирой по адресу: {address}";
        string[] lines = kind switch
        {
            ClaimKind.Connected =>
            [
                "Уведомление о наличии задолженности и приостановлении оказания услуг (отключении антенны)",
                "Уважаемый абонент!",
                $"Уведомляем Вас о наличии задолженности по оплате за техническое обслуживание системы коллективного приёма телевидения {service}.",
                "Напоминаем, что между Вами и нашей организацией заключен договор на абонентское обслуживание, в соответствии с которым на абонента возложена обязанность по своевременной оплате оказываемых услуг.",
                $"На сегодняшний день Ваша задолженность составляет {sum}.",
                "Обращаем Ваше внимание на то, что антенна на данный момент остается подключенной. Поскольку услуга продолжает фактически предоставляться, сумма долга увеличивается ежемесячно за счёт текущих начислений абонентской платы.",
                "Просим погасить накопившуюся задолженность в течение 10 (десяти) календарных дней с момента получения настоящего уведомления.",
                Pay,
                "В связи с длительным неисполнением обязательств по оплате, мы будем вынуждены в одностороннем порядке приостановить оказание услуг и произвести отключение антенны за неуплату.",
                "Также в случае игнорирования данного уведомления, помимо отключения услуги, материалы будут направлены в суд для принудительного взыскания долга, а также судебных издержек."
            ],
            ClaimKind.DisconnectedForDebt =>
            [
                "Досудебное уведомление о погашении задолженности",
                "Уважаемый абонент!",
                $"Уведомляем Вас о наличии задолженности по оплате за техническое обслуживание системы коллективного приёма телевидения {service}.",
                $"В связи с наличием непогашенной задолженности Ваша квартира была отключена от услуг нашей компании {date} года. С этой даты начисления абонентской платы за услуги по техническому обслуживанию систем коллективного приема телевидения по адресу: {address} не производятся.",
                $"На момент отключения антенны задолженность составляет {sum}.",
                "Просим Вас погасить указанную задолженность в течение 10 (десяти) календарных дней с момента получения настоящего уведомления.",
                Pay,
                "Если Вы являетесь новым собственником квартиры; считаете, что задолженность не относится к Вашему периоду проживания; уже произвели оплату указанной суммы, просим Вас в тот же 10-дневный срок сообщить об этом в нашу компанию. Приложите, пожалуйста, подтверждающие документы (выписка из ЕГРН, договор купли продажи, чек/платёжное поручение об оплате и т. д.).",
                $"В случае непоступления оплаты или отсутствия обратной связи в установленный срок мы будем вынуждены обратиться в суд с иском о взыскании суммы основного долга — {debt.ToString("0.00", System.Globalization.CultureInfo.GetCultureInfo("ru-RU"))} руб., неустойки за просрочку, расходов по уплате государственной пошлины и иных судебных издержек.",
                "Благодарим за понимание и своевременное решение вопроса."
            ],
            _ =>
            [
                "Уведомление о наличии задолженности",
                "Уважаемый абонент!",
                $"На основании Вашего заявления от {date} г. начисление платы за техническое обслуживание системы коллективного приёма телевидения {service}, официально прекращено. Предоставление услуги завершено, новые начисления по Вашему адресу не производятся.",
                "Напоминаем, что согласно ст. 540, ст. 781 и ст. 1102 Гражданского кодекса РФ, отсутствие письменного договора не освобождает потребителя от обязанности оплатить фактически оказанные ему услуги за весь период их предоставления до момента подачи заявления об отказе от них.",
                $"На дату прекращения обслуживания по Вашему адресу зафиксирована задолженность за ранее предоставленные услуги в размере {sum}.",
                "Просим Вас в добровольном порядке погасить имеющуюся задолженность в течение 10 (десяти) календарных дней с момента получения настоящего уведомления для окончательного закрытия лицевого счёта.",
                Pay,
                "В случае игнорирования данного уведомления и неоплаты фиксированного остатка долга в установленный срок, мы будем вынуждены направить материалы в суд для принудительного взыскания задолженности в судебном порядке. Обращаем Ваше внимание, что в данном случае сумма, подлежащая взысканию, увеличится на размер государственной пошлины и иных судебных издержек."
            ]
        };
        return string.Join("\n\n", lines);
    }
}
